CREATE FUNCTION twinsight.touch_catalog_record() RETURNS trigger LANGUAGE plpgsql SET search_path='' AS $$
BEGIN NEW.updated_at := clock_timestamp(); RETURN NEW; END $$;
CREATE TRIGGER catalog_record_updated BEFORE UPDATE ON twinsight.catalog_records
 FOR EACH ROW WHEN(to_jsonb(OLD) IS DISTINCT FROM to_jsonb(NEW)) EXECUTE FUNCTION twinsight.touch_catalog_record();

-- Private trigger only. Definer permits append-only audit without granting clients write access.
CREATE FUNCTION twinsight.audit_catalog_change() RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path='' AS $$
DECLARE b jsonb; a jsonb; k text;
BEGIN
 IF TG_OP <> 'INSERT' THEN b := to_jsonb(OLD); END IF;
 IF TG_OP <> 'DELETE' THEN a := to_jsonb(NEW); END IF;
 IF TG_OP='UPDATE' AND b=a THEN RETURN NULL; END IF;
 IF TG_TABLE_NAME='catalog_records' THEN
   IF b IS NOT NULL THEN b := (b - 'details') || jsonb_build_object('details_md5',md5((b->'details')::text)); END IF;
   IF a IS NOT NULL THEN a := (a - 'details') || jsonb_build_object('details_md5',md5((a->'details')::text)); END IF;
 END IF;
 k := coalesce(a->>'record_id',b->>'record_id',a->>'calibration_id',b->>'calibration_id');
 INSERT INTO twinsight.catalog_audit(table_name,record_key,operation,database_actor,before_data,after_data)
 VALUES(TG_TABLE_NAME,k,TG_OP,session_user,b,a);
 RETURN NULL;
END $$;
CREATE TRIGGER audit_catalog_record AFTER INSERT OR UPDATE OR DELETE ON twinsight.catalog_records
 FOR EACH ROW EXECUTE FUNCTION twinsight.audit_catalog_change();
CREATE TRIGGER audit_calibration AFTER INSERT ON twinsight.calibration_versions
 FOR EACH ROW EXECUTE FUNCTION twinsight.audit_catalog_change();
CREATE TRIGGER audit_binding AFTER INSERT ON twinsight.experiment_bindings
 FOR EACH ROW EXECUTE FUNCTION twinsight.audit_catalog_change();

CREATE FUNCTION twinsight.validate_experiment_binding() RETURNS trigger LANGUAGE plpgsql SET search_path='' AS $$
BEGIN
 IF NOT EXISTS(SELECT 1 FROM twinsight.catalog_logs WHERE record_id=NEW.record_id AND stream=NEW.stream) THEN
   RAISE EXCEPTION 'Binding stream does not exist' USING ERRCODE='23514';
 END IF;
 IF EXISTS(SELECT 1 FROM twinsight.catalog_logs WHERE record_id=NEW.record_id AND stream=NEW.stream AND
    ((message::jsonb->>'camera_id') IS DISTINCT FROM NEW.camera_id OR
     (message::jsonb->>'width')::integer IS DISTINCT FROM NEW.image_width OR
     (message::jsonb->>'height')::integer IS DISTINCT FROM NEW.image_height)) THEN
   RAISE EXCEPTION 'Binding camera or resolution mismatch' USING ERRCODE='23514';
 END IF;
 IF NEW.calibration_id IS NOT NULL AND NOT EXISTS(SELECT 1 FROM twinsight.calibration_versions
    WHERE calibration_id=NEW.calibration_id AND camera_id=NEW.camera_id AND image_width=NEW.image_width AND image_height=NEW.image_height) THEN
   RAISE EXCEPTION 'Calibration camera or resolution mismatch' USING ERRCODE='23514';
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER validate_binding BEFORE INSERT ON twinsight.experiment_bindings
 FOR EACH ROW EXECUTE FUNCTION twinsight.validate_experiment_binding();
REVOKE ALL ON FUNCTION twinsight.touch_catalog_record(),twinsight.audit_catalog_change(),twinsight.validate_experiment_binding() FROM PUBLIC,anon,authenticated;
